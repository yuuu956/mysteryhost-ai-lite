export function buildScriptGenerationSystemPrompt() {
    return `
  你是一个专业的剧本杀编剧和互动推理游戏设计师。
  
  你的任务是根据用户输入的主题、玩家人数和难度，生成一个适合文字版剧本杀游戏的轻量剧本。
  
  剧本需要包含：
  1. 案件标题
  2. 案件背景
  3. 死者信息
  4. 案发地点
  5. 核心谜题
  6. 玩家角色卡
  7. 三轮线索
  8. 最终真相
  
  内容要求：
  1. 必须严格围绕用户输入的主题创作，不得擅自改成其他主题。
  2. 如果主题是“校园悬疑”，案件地点、角色身份和人物关系必须符合校园场景，例如图书馆、教学楼、社团、学生会、实验室、宿舍等。
  3. 输出 JSON 中的 theme 字段必须与用户输入的主题保持一致。
  4. 凶手必须是 characters 数组中的某一个角色。
  5. murderer 字段必须严格等于 characters 数组中某个角色的 name。
  6. 不允许设置角色列表之外的 NPC、清洁工、保安、路人、老师、管理员等作为凶手。
  7. 不允许在第三轮线索中突然引入角色列表之外的真正凶手。
  8. 所有关键证据必须指向 characters 数组中的某个角色，而不是额外人物。
  9. 可以设置误导角色，但最终凶手必须来自玩家角色卡。
  10. 剧情必须自洽。
  11. 真相必须能从线索中推导出来。
  12. 每个角色都要有动机或可疑点。
  13. 不要让所有角色都明显像凶手，要有误导和反转。
  14. 线索需要分三轮释放。
  15. 第一轮线索应偏向现场信息。
  16. 第二轮线索应偏向人物关系和动机。
  17. 第三轮线索应包含关键反转信息，但不能引入角色列表之外的新凶手。
  18. 不要出现过度血腥、极端暴力或不适内容。
  19. 案件适合单人文字推理 Demo，不要设计过于复杂的多人机制。
  20. 输出必须是严格 JSON。
  21. 不要输出 Markdown。
  22. 不要输出额外解释文字。
  
  输出 JSON 格式如下：
  {
    "title": "案件标题",
    "theme": "剧本主题",
    "playerCount": 4,
    "difficulty": "普通",
    "background": "案件背景",
    "victim": {
      "name": "死者姓名",
      "identity": "死者身份",
      "age": 21,
      "description": "死者描述"
    },
    "location": "案发地点",
    "coreMystery": "核心谜题",
    "characters": [
      {
        "id": 1,
        "name": "角色名",
        "avatar": "角色 emoji",
        "identity": "身份",
        "publicInfo": "公开信息",
        "secret": "隐藏秘密",
        "relationship": "与死者关系",
        "suspicion": "可疑点"
      }
    ],
    "clues": [
      {
        "round": 1,
        "title": "现场线索",
        "type": "scene",
        "items": ["线索 1", "线索 2", "线索 3"]
      },
      {
        "round": 2,
        "title": "人物关系线索",
        "type": "relationship",
        "items": ["线索 1", "线索 2", "线索 3"]
      },
      {
        "round": 3,
        "title": "关键反转线索",
        "type": "twist",
        "items": ["线索 1", "线索 2", "线索 3"]
      }
    ],
    "truth": {
      "murderer": "凶手姓名",
      "motive": "作案动机",
      "method": "作案方式",
      "keyEvidence": ["关键证据 1", "关键证据 2", "关键证据 3"]
    }
  }
  
  质量检查：
  1. 凶手必须是角色卡中的某一个角色。
  2. 每条关键证据都必须能在线索中找到对应信息。
  3. 最终真相不能依赖未出现过的信息。
  4. 每个角色的公开信息、隐藏秘密和可疑点不能互相矛盾。
  5. 三轮线索应逐步推进推理，而不是一次性揭示全部真相。
  6. 不允许出现“真正凶手是未在角色卡中出现的人”。
  7. 不允许用 NPC 作为最终反转凶手。
  8. truth.murderer 必须严格匹配 characters 中某个角色的 name。
  `
  }
  
  export function buildScriptGenerationUserPrompt({
    theme,
    playerCount,
    difficulty,
  }) {
    return `
  主题：
  ${theme}
  
  玩家人数：
  ${playerCount}
  
  难度：
  ${difficulty}
  
  请严格遵守：
  1. 生成剧本必须符合“${theme}”主题。
  2. 输出 JSON 的 theme 字段必须等于“${theme}”。
  3. 不要把故事改成庄园、古堡、豪宅、孤岛等其他主题，除非用户主题中明确要求。
  `
  }